#!/usr/bin/env node
// BND-006 followup — regenerate src/types/database.ts from the live
// Supabase schema.
//
// Usage:
//   SUPABASE_ACCESS_TOKEN=... SUPABASE_PROJECT_ID=... \
//     node scripts/generate-supabase-types.mjs
//
//   pnpm run types:gen   # regenerate + write
//   pnpm run types:check # regenerate + fail CI if git-diff is non-empty
//
// We hit the Supabase Management API directly rather than the
// `supabase` CLI so CI doesn't need to install the full toolchain.
// The same endpoint `supabase gen types typescript --project-id=…`
// uses under the hood.
//
// Required env:
//   SUPABASE_ACCESS_TOKEN  personal access token, scope `read:projects`
//   SUPABASE_PROJECT_ID    project ref (the ~20-char id in project URL)

import { writeFileSync } from "node:fs";

const HEADER = `// Generated by \`supabase gen types typescript\` via the Supabase MCP.
// Re-run after every migration. Do not edit by hand.
//
// Regeneration: \`pnpm run types:gen\` (requires SUPABASE_ACCESS_TOKEN +
// SUPABASE_PROJECT_ID env). CI verifies this file matches the live
// schema via \`pnpm run types:check\`.

`;

const OUT = "src/types/database.ts";

const token = process.env.SUPABASE_ACCESS_TOKEN;
const projectId = process.env.SUPABASE_PROJECT_ID;

if (!token || !projectId) {
  console.error(
    "Missing env: set SUPABASE_ACCESS_TOKEN and SUPABASE_PROJECT_ID.",
  );
  process.exit(1);
}

const url = `https://api.supabase.com/v1/projects/${projectId}/types/typescript?included_schemas=public`;

const res = await fetch(url, {
  headers: {
    Authorization: `Bearer ${token}`,
    Accept: "application/json",
  },
});

if (!res.ok) {
  const body = await res.text();
  console.error(
    `Supabase API returned ${res.status}: ${body.slice(0, 500)}`,
  );
  process.exit(2);
}

const payload = await res.json();
const body = typeof payload === "string" ? payload : payload.types;

if (typeof body !== "string" || body.length === 0) {
  console.error("Unexpected response shape:", payload);
  process.exit(3);
}

writeFileSync(OUT, HEADER + body);
console.log(`Wrote ${OUT} (${body.length} bytes).`);
